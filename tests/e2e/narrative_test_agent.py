"""Narrative quality evaluator for full game sessions.

Uses a higher-tier LLM as a senior narrative-design judge. Unlike
``TesterAgent``, which does single-turn YES/NO checks, this agent consumes
an entire ``SessionTranscript`` and grades it across six rubrics: Story,
Turns, Scenes, Confrontation, Memory, and Autonomy.

Soft reporting only — the judge returns structured scores + reasoning, but
this module does not enforce thresholds. The calling test decides whether
to fail on a score.
"""

import json
import os
import re
import types
from typing import Any, Mapping

from tests.e2e.narrative_report import NarrativeReport, RubricScore
from tests.e2e.session_transcript import SessionTranscript

_ANTHROPIC_DEFAULT_MODEL = "claude-opus-4-6"
_OPENAI_DEFAULT_MODEL = "gpt-5.4"
_JUDGE_MAX_TOKENS = 800
_MIN_SCORE = 1
_MAX_SCORE = 10
_TOTAL_ATTEMPTS = 2
_ERROR_SNIPPET_LEN = 200
_MODEL_ENV_VAR = "NARRATIVE_TESTER_MODEL"
_BACKEND_ANTHROPIC = "anthropic"
_BACKEND_OPENAI = "openai"

RUBRIC_STORY = "STORY"
RUBRIC_TURNS = "TURNS"
RUBRIC_SCENES = "SCENES"
RUBRIC_CONFRONTATION = "CONFRONTATION"
RUBRIC_MEMORY = "MEMORY"
RUBRIC_AUTONOMY = "AUTONOMY"

RUBRICS: tuple[str, ...] = (
    RUBRIC_STORY,
    RUBRIC_TURNS,
    RUBRIC_SCENES,
    RUBRIC_CONFRONTATION,
    RUBRIC_MEMORY,
    RUBRIC_AUTONOMY,
)

_RUBRIC_CRITERIA: Mapping[str, str] = types.MappingProxyType(
    {
        RUBRIC_STORY: (
            "Evaluate the session's overall narrative arc. Look for "
            "tonal consistency, forward motion, an opening hook that "
            "pays off later, and meaningful stakes for the protagonist."
        ),
        RUBRIC_TURNS: (
            "Evaluate turn-by-turn responsiveness. Each narration "
            "should react to the player's action in a plausible way, "
            "with appropriate time progression and no non-sequiturs "
            "or contradictions between turns."
        ),
        RUBRIC_SCENES: (
            "Evaluate scene construction. Look for vivid atmosphere, "
            "sensory detail, NPCs present and acting in place, clean "
            "scene transitions, and continuity of location as the "
            "player moves around."
        ),
        RUBRIC_CONFRONTATION: (
            "Evaluate any confrontations, duels, or combat. Look for "
            "tension, clear stakes, earned dice outcomes, NPCs with "
            "motivation to fight, and aftermath reflected in later "
            "turns. If no combat occurs, grade the closest tense "
            "social encounter instead."
        ),
        RUBRIC_MEMORY: (
            "Evaluate narrative memory and continuity. NPCs revisited "
            "later should remember past interactions; referenced "
            "events must match what actually happened earlier; world "
            "state (locations, items, consequences) must persist."
        ),
        RUBRIC_AUTONOMY: (
            "Evaluate the autonomy of the world and its NPCs. NPCs "
            "should act without being prompted by the player, the "
            "game clock should advance organically, and the world "
            "should feel alive between player actions rather than "
            "frozen."
        ),
    },
)

_SYSTEM_PROMPT = (
    "You are a senior narrative designer grading an interactive fiction "
    "session generated by an AI game engine. You will be given a "
    "captured transcript and one specific rubric. Grade strictly but "
    "fairly on a scale from 1 (broken) to 10 (publishable quality). "
    "Respond with ONLY a single JSON object — no prose, no markdown "
    'fence. Schema: {"score": <int 1-10>, "reasoning": "<1-3 '
    'sentences>", "issues": ["<short bullet>", ...]}. The "issues" '
    "array may be empty if nothing is wrong."
)

_JSON_OBJECT_PATTERN = re.compile(r"\{.*\}", re.DOTALL)


class _JudgeAPIError(RuntimeError):
    """Raised for SDK-level errors that warrant one retry."""


class NarrativeTestAgent:
    """LLM-as-judge evaluator over full session transcripts.

    Prefers Anthropic (``claude-opus-4-6``) when ``ANTHROPIC_API_KEY`` is
    set, otherwise falls back to OpenAI (``gpt-5.4``). Override the model
    with the ``NARRATIVE_TESTER_MODEL`` environment variable.
    """

    # These attributes are polymorphic across SDKs (anthropic vs openai),
    # so they're declared as Any to keep mypy happy without suppressions.
    _backend: str
    _client: Any
    _anthropic: Any
    model: str

    def __init__(self) -> None:
        if os.environ.get("ANTHROPIC_API_KEY"):
            import anthropic

            self._backend = _BACKEND_ANTHROPIC
            self._client = anthropic.Anthropic()
            self._anthropic = anthropic
            self.model = os.environ.get(_MODEL_ENV_VAR, _ANTHROPIC_DEFAULT_MODEL)
        elif os.environ.get("OPENAI_API_KEY"):
            from openai import OpenAI

            self._backend = _BACKEND_OPENAI
            self._client = OpenAI()
            self.model = os.environ.get(_MODEL_ENV_VAR, _OPENAI_DEFAULT_MODEL)
        else:
            raise RuntimeError(
                "NarrativeTestAgent requires ANTHROPIC_API_KEY or OPENAI_API_KEY",
            )

    def evaluate(self, transcript: SessionTranscript, rubric: str) -> RubricScore:
        """Grade a single rubric over the full transcript."""
        if rubric not in _RUBRIC_CRITERIA:
            raise ValueError(f"Unknown rubric: {rubric!r}")

        user_message = _build_user_prompt(transcript, rubric)
        last_error: Exception | None = None
        attempt = 0
        while attempt < _TOTAL_ATTEMPTS:
            try:
                return self._attempt_rubric(rubric, user_message)
            except (_JudgeAPIError, ValueError) as exc:
                last_error = exc
            attempt += 1
        raise RuntimeError(
            f"NarrativeTestAgent failed rubric {rubric} after retry: {last_error}",
        )

    def evaluate_session(self, transcript: SessionTranscript) -> NarrativeReport:
        """Grade all six rubrics sequentially over the full transcript."""
        scores: list[RubricScore] = []
        for rubric in RUBRICS:
            scores.append(self.evaluate(transcript, rubric))
        return NarrativeReport(model=self.model, scores=tuple(scores))

    def _attempt_rubric(self, rubric: str, user_message: str) -> RubricScore:
        raw_reply = self._ask(user_message)
        return _parse_rubric_response(rubric, raw_reply)

    def _ask(self, user_message: str) -> str:
        if self._backend == _BACKEND_ANTHROPIC:
            return self._ask_anthropic(user_message)
        return self._ask_openai(user_message)

    def _ask_anthropic(self, user_message: str) -> str:
        try:
            response = self._client.messages.create(
                model=self.model,
                max_tokens=_JUDGE_MAX_TOKENS,
                system=_SYSTEM_PROMPT,
                messages=[{"role": "user", "content": user_message}],
            )
        except self._anthropic.APIStatusError as exc:
            current_model = self.model
            status = exc.status_code
            raise _JudgeAPIError(
                f"Anthropic API error (model={current_model}, status={status})",
            ) from exc
        except self._anthropic.APIConnectionError as exc:
            raise _JudgeAPIError(
                "NarrativeTestAgent lost connection to Anthropic API",
            ) from exc
        return response.content[0].text.strip()

    def _ask_openai(self, user_message: str) -> str:
        response = self._client.chat.completions.create(
            model=self.model,
            max_completion_tokens=_JUDGE_MAX_TOKENS,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": _SYSTEM_PROMPT},
                {"role": "user", "content": user_message},
            ],
        )
        return (response.choices[0].message.content or "").strip()


def _build_user_prompt(transcript: SessionTranscript, rubric: str) -> str:
    criteria = _RUBRIC_CRITERIA[rubric]
    rendered = transcript.render_for_judge()
    return (
        f"RUBRIC: {rubric}\n\n"
        f"CRITERIA: {criteria}\n\n"
        "Grade this transcript on the rubric above. Return only the JSON "
        "object described in the system instructions.\n\n"
        "=== TRANSCRIPT ===\n"
        f"{rendered}"
    )


def _parse_rubric_response(rubric: str, raw_reply: str) -> RubricScore:
    parsed = _extract_json_object(raw_reply)
    return RubricScore(
        rubric=rubric,
        score=_coerce_score(parsed.get("score")),
        reasoning=str(parsed.get("reasoning", "")).strip(),
        issues=_extract_issues(rubric, parsed.get("issues") or []),
    )


def _extract_issues(rubric: str, raw_issues: object) -> tuple[str, ...]:
    if not isinstance(raw_issues, list):
        actual_type = type(raw_issues).__name__
        raise ValueError(f"Rubric {rubric}: 'issues' must be a list, got {actual_type}")
    stripped = [str(entry).strip() for entry in raw_issues]
    return tuple(entry for entry in stripped if entry)


def _extract_json_object(raw_reply: str) -> dict:
    try:
        parsed = json.loads(raw_reply)
    except json.JSONDecodeError:
        match = _JSON_OBJECT_PATTERN.search(raw_reply)
        if match is None:
            snippet = raw_reply[:_ERROR_SNIPPET_LEN]
            raise ValueError(f"Judge reply is not valid JSON: {snippet!r}")
        parsed = json.loads(match.group(0))
    if not isinstance(parsed, dict):
        actual_type = type(parsed).__name__
        raise ValueError(f"Judge reply must be a JSON object, got {actual_type}")
    return parsed


def _coerce_score(raw_score: object) -> int:
    if isinstance(raw_score, bool) or not isinstance(raw_score, (int, str)):
        raise ValueError(f"Judge score must be int-like, got {raw_score!r}")
    if isinstance(raw_score, int):
        parsed = raw_score
    else:
        try:
            parsed = int(raw_score.strip())
        except ValueError as exc:
            raise ValueError(f"Judge score must be int-like, got {raw_score!r}") from exc
    if parsed < _MIN_SCORE or parsed > _MAX_SCORE:
        raise ValueError(f"Judge score must be in [{_MIN_SCORE}, {_MAX_SCORE}], got {parsed}")
    return parsed
