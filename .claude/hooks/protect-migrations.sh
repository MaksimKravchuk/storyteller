#!/usr/bin/env bash
# PreToolUse hook (Edit|Write|MultiEdit): block edits to *already-committed*
# Alembic migrations. Project policy: a revision under alembic/versions/ that
# exists in a commit may already be applied in another environment — mutating
# it desyncs schema history. New schema changes must be a *new* revision.
#
# Heuristic: deny iff the target path is under alembic/versions/ AND exists in
# HEAD (committed). A freshly `alembic revision --autogenerate`'d file is not
# in HEAD — untracked OR merely staged — so the normal autogenerate-then-edit
# flow stays unblocked right up until the revision is committed.
#
# Fail-open posture (matches require-skill.sh): any misconfiguration — no jq,
# not a git repo, unreadable input — allows the tool with a stderr warning.
# Wedging a legitimate edit on a hook bug is worse than missing one guard.

set -euo pipefail
cd "$(dirname "$0")/../.."

allow() {
  printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"allow"}}\n'
}

if ! command -v jq >/dev/null 2>&1; then
  echo "protect-migrations.sh: jq not found (allowing)" >&2
  allow
  exit 0
fi

path="$(jq -r '.tool_input.file_path // ""' <<<"$(cat)")"

if [ -z "$path" ]; then
  allow
  exit 0
fi

# Hot path: this hook fires on every Edit/Write/MultiEdit. A pure-shell
# substring test bails before forking any git subprocess for the ~99% of
# edits that aren't migrations at all. A false match here (e.g. a path that
# merely contains the substring) is harmless — the precise repo-relative
# re-check below still gates it correctly.
case "$path" in
  *alembic/versions/*) ;;
  *)
    allow
    exit 0
    ;;
esac

# Only now (rare: edit looks like a migration) is it worth resolving the
# repo root to normalize an absolute path and confirm the prefix precisely.
repo_root="$(git rev-parse --show-toplevel 2>/dev/null || echo "")"
if [ -z "$repo_root" ]; then
  echo "protect-migrations.sh: not a git repo (allowing)" >&2
  allow
  exit 0
fi
case "$path" in
  /*) rel="${path#"$repo_root"/}" ;;
  *)  rel="$path" ;;
esac

case "$rel" in
  alembic/versions/*) ;;
  *)
    allow
    exit 0
    ;;
esac

# In HEAD (committed) → protected. Untracked or staged-only (autogenerated,
# not yet committed) → allowed, so the autogenerate-then-edit flow works.
if git cat-file -e "HEAD:$rel" 2>/dev/null; then
  reason="BLOCKED: $rel is a committed Alembic migration. It may already be applied in other environments, so editing it desyncs schema history. Generate a NEW revision instead (uv run alembic revision --autogenerate -m \"...\"), and remember to update db/converters.py for any domain<->ORM change. If you genuinely must amend this revision, ask the user to confirm out loud first."
  jq -nc --arg r "$reason" '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$r}}'
  exit 0
fi

allow
exit 0
