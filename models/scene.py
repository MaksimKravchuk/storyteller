from __future__ import annotations

from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, field_validator

from models.base_model import StorytellerBase


def clean_names(names: list[str], context: str) -> list[str]:
    """Strip whitespace and drop blanks, raising when no usable name remains.

    Shared by :class:`PointOfInterest` and :class:`models.visible_entity.VisibleEntity`
    so the contract — at least one non-empty alias — has a single enforcement point.
    """
    cleaned = [name.strip() for name in names if name and name.strip()]
    if not cleaned:
        raise ValueError("{0}.names must contain at least one non-empty name".format(context))
    return cleaned


class PointOfInterest(StorytellerBase):
    """A named, addressable feature inside a scene or location.

    ``names`` is the list of player-visible aliases. The first element
    is the primary label (used when a single name must be picked). The
    rest are acceptable synonyms: the Narrator may alternate between
    them for natural prose, and the entity-markup post-match wraps any
    of them.
    """

    names: list[str]

    @property
    def primary_name(self) -> str:
        """Return the first alias — used anywhere a single label is needed."""
        return self.names[0]

    @field_validator("names")
    @classmethod
    def _names_non_empty(cls, raw: list[str]) -> list[str]:
        return clean_names(raw, "PointOfInterest")


class SceneNPC(BaseModel):
    """Lightweight NPC descriptor within a scene.

    Created by Scene Builder from LLM output.  The Director
    initialises it (generates an ``NPCCard`` + ``Actor``)
    deterministically on every turn.

    SceneNPC intentionally does *not* inherit ``StorytellerBase``:
    its identity is its role plus the UUID of a separately-generated
    ``NPCCard``, so it has no UUID of its own.
    """

    role: str  # Short role from LLM, e.g. "guard", "merchant"
    uuid: UUID | None = None  # Set after NPCCard generation


def coerce_point_of_interest(entry: Any) -> PointOfInterest:
    """Convert one heterogeneous POI entry to a ``PointOfInterest`` instance.

    Accepts the three shapes producers commonly emit: an existing
    ``PointOfInterest``, a bare legacy string (promoted to a single-alias
    POI), or a dict matching :class:`PointOfInterest`'s schema (the new
    ``{"names": [...]}`` form that carries head-noun aliases).
    """
    if isinstance(entry, PointOfInterest):
        return entry
    if isinstance(entry, str):
        return PointOfInterest(names=[entry])
    if isinstance(entry, dict):
        return PointOfInterest.model_validate(entry)
    raise TypeError(
        "points_of_interest entry must be str, dict, or PointOfInterest, got {0}".format(type(entry)),
    )


def _coerce_points_of_interest(raw: Any) -> list[PointOfInterest]:
    """Accept legacy ``list[str]`` and new ``list[PointOfInterest|dict]`` inputs.

    The LLM scene-response schema still returns bare strings; historical
    test fixtures, benchmark scenarios, and persisted JSON columns also
    use bare strings. Promoting :class:`PointOfInterest` to first-class
    while keeping backward compatibility is cheaper than migrating every
    producer at once.
    """
    if raw is None:
        return []
    return [coerce_point_of_interest(entry) for entry in raw]


class Scene(StorytellerBase):
    """A snapshot of a specific place at a specific time.

    Generated by the Scene Builder agent and then narrated by the Narrator.
    """

    model_config = ConfigDict(validate_assignment=True)

    location_id: UUID
    description: str = ""
    npcs_present: list[SceneNPC] = []
    points_of_interest: list[PointOfInterest] = []
    ambient_description: str = ""
    time_of_day: str = "day"
    narrated_text: str = ""  # Filled by the Narrator

    @field_validator("points_of_interest", mode="before")
    @classmethod
    def _coerce_pois(cls, raw: Any) -> list[PointOfInterest]:
        return _coerce_points_of_interest(raw)
